//! The runner: a generated crate of two files that links one app to the
//! preview's host.
//!
//! An app is a library that registers itself with `morningstar::app!` (ADR
//! 0005): it exports `__morningstar_create_app` and has no `main`. On a
//! phone the platform crate, linked into the same library, calls that
//! function. Here a generated binary crate depends on the app and on this
//! crate, declares the same function and hands it to [`crate::host::run`].
//! The app is linked statically, by the same compiler, like any Rust
//! dependency: nothing is loaded at run time and no app adds a line for it.
//!
//! The crate is its own workspace under `target/preview/<app>/runner`, so
//! that it works for an app in any workspace, and it builds into the app's
//! own target directory, where whatever the app and the framework have
//! already compiled is reused.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// What a runner is generated from.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Runner {
    /// The app's Cargo package, such as `barua-talk`.
    pub package: String,
    /// The directory of the app's `Cargo.toml`.
    pub app_dir: PathBuf,
    /// The directory of this crate's `Cargo.toml`.
    pub preview_dir: PathBuf,
    /// Whether this copy of the preview is a release from crates.io (as
    /// under `cargo install morningstar-cli`) rather than a checkout of the
    /// repository. A release's sources sit in Cargo's cache, which Cargo
    /// may clean, so the runner names the same release by its version
    /// instead of by that path (ADR 0045).
    pub released: bool,
}

impl Runner {
    /// The runner for an app, linked to this copy of the preview.
    pub fn new(package: &str, app_dir: &Path) -> Self {
        let preview_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        Self {
            package: package.to_owned(),
            app_dir: app_dir.to_owned(),
            // `cargo package` keeps the manifest as written beside the one
            // it normalises, in every published crate and in no checkout.
            released: preview_dir.join("Cargo.toml.orig").is_file(),
            preview_dir,
        }
    }

    /// The name of the runner's package and of the binary it builds.
    pub fn binary_name(&self) -> String {
        format!("preview-{}", self.package)
    }

    /// The runner's `Cargo.toml`.
    pub fn manifest(&self) -> String {
        format!(
            "\
# Generated by morningstar-preview. Do not edit: it is written again.
[package]
name = {name}
version = \"0.0.0\"
edition = \"2024\"
publish = false

# Its own workspace: it lives under the app's target directory.
[workspace]

[dependencies]
app = {{ package = {package}, path = {app} }}
morningstar-preview = {preview}
",
            name = toml_string(&self.binary_name()),
            package = toml_string(&self.package),
            app = toml_string(&self.app_dir.display().to_string()),
            preview = if self.released {
                format!("\"={}\"", env!("CARGO_PKG_VERSION"))
            } else {
                format!(
                    "{{ path = {} }}",
                    toml_string(&self.preview_dir.display().to_string())
                )
            },
        )
    }

    /// The runner's `src/main.rs`.
    pub fn main_rs(&self) -> String {
        "\
// Generated by morningstar-preview. Do not edit: it is written again.

// Naming the app is what links it, and with it the function `app!` exports.
use app as _;

unsafe extern \"Rust\" {
    fn __morningstar_create_app() -> Box<dyn morningstar_preview::App>;
}

fn create() -> Box<dyn morningstar_preview::App> {
    // SAFETY: defined by `morningstar::app!` in the app, with this
    // signature, and compiled by the same compiler into this binary.
    unsafe { __morningstar_create_app() }
}

fn main() -> std::process::ExitCode {
    morningstar_preview::host::run(create)
}
"
        .to_owned()
    }

    /// Writes the runner into `dir`, touching only what differs, so that a
    /// second run builds nothing. Returns the path of its `Cargo.toml`.
    pub fn write(&self, dir: &Path) -> io::Result<PathBuf> {
        fs::create_dir_all(dir.join("src"))?;
        let manifest = dir.join("Cargo.toml");
        write_if_changed(&manifest, &self.manifest())?;
        write_if_changed(&dir.join("src/main.rs"), &self.main_rs())?;
        Ok(manifest)
    }
}

/// Gives the runner the versions the app's workspace is locked to: a copy
/// of its `Cargo.lock`, taken when the runner has none or the workspace's
/// is newer. Cargo then drops what the runner does not use and adds
/// nothing the lock already decides.
pub fn sync_lock(workspace_root: &Path, runner_dir: &Path) -> io::Result<bool> {
    let from = workspace_root.join("Cargo.lock");
    let to = runner_dir.join("Cargo.lock");
    let Ok(source) = fs::metadata(&from) else {
        return Ok(false);
    };
    let newer = match fs::metadata(&to) {
        Ok(existing) => match (source.modified(), existing.modified()) {
            (Ok(source), Ok(existing)) => source > existing,
            _ => true,
        },
        Err(_) => true,
    };
    if newer {
        fs::copy(&from, &to)?;
    }
    Ok(newer)
}

fn write_if_changed(path: &Path, contents: &str) -> io::Result<()> {
    if fs::read_to_string(path).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    fs::write(path, contents)
}

/// A TOML basic string: quoted, with what must be escaped escaped.
fn toml_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ch if ch.is_control() => out.push_str(&format!("\\u{:04X}", ch as u32)),
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

/// What the supervisor needs from `cargo metadata --no-deps` besides the
/// app's identity: where things are built, and what to watch.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Workspace {
    /// The directory of the workspace's `Cargo.toml` and `Cargo.lock`.
    pub root: PathBuf,
    /// Where the workspace builds: its `target`.
    pub target_dir: PathBuf,
    /// The directory of every member's `Cargo.toml`: the app, the
    /// framework's crates, and the rest of the workspace.
    pub members: Vec<PathBuf>,
}

impl Workspace {
    /// Reads the three from the output of `cargo metadata --no-deps`.
    ///
    /// The values are found by their keys rather than by parsing the whole
    /// document: Cargo writes each of these keys only with this meaning,
    /// and `--no-deps` lists workspace members alone.
    pub fn from_cargo_metadata(metadata: &str) -> Option<Self> {
        let root = PathBuf::from(json_strings(metadata, "workspace_root").next()?);
        let target_dir = PathBuf::from(json_strings(metadata, "target_directory").next()?);
        let mut members: Vec<PathBuf> = json_strings(metadata, "manifest_path")
            .filter_map(|manifest| Path::new(&manifest).parent().map(Path::to_owned))
            .collect();
        members.sort();
        members.dedup();
        Some(Self {
            root,
            target_dir,
            members,
        })
    }
}

/// Every string value of `"key":"..."` in a JSON document, unescaped.
fn json_strings<'a>(document: &'a str, key: &'a str) -> impl Iterator<Item = String> + 'a {
    let needle = format!("\"{key}\":\"");
    let mut rest = document;
    std::iter::from_fn(move || {
        let start = rest.find(&needle)? + needle.len();
        let mut value = String::new();
        let mut chars = rest[start..].char_indices();
        let end = loop {
            let (index, ch) = chars.next()?;
            match ch {
                '"' => break start + index + 1,
                '\\' => match chars.next()?.1 {
                    'n' => value.push('\n'),
                    't' => value.push('\t'),
                    'r' => value.push('\r'),
                    'u' => {
                        let code: String = chars.by_ref().take(4).map(|(_, ch)| ch).collect();
                        value.push(
                            u32::from_str_radix(&code, 16)
                                .ok()
                                .and_then(char::from_u32)
                                .unwrap_or('\u{FFFD}'),
                        );
                    }
                    other => value.push(other),
                },
                ch => value.push(ch),
            }
        };
        rest = &rest[end..];
        Some(value)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn runner() -> Runner {
        Runner {
            package: "barua-talk".to_owned(),
            app_dir: PathBuf::from("/work/Morning Star/examples/barua-talk"),
            preview_dir: PathBuf::from("/work/Morning Star/tools/morningstar-preview"),
            released: false,
        }
    }

    #[test]
    fn the_manifest_names_the_app_and_the_preview_by_path() {
        let manifest = runner().manifest();
        assert!(manifest.contains("name = \"preview-barua-talk\""));
        assert!(manifest.contains(
            "app = { package = \"barua-talk\", path = \"/work/Morning Star/examples/barua-talk\" }"
        ));
        assert!(manifest.contains(
            "morningstar-preview = { path = \"/work/Morning Star/tools/morningstar-preview\" }"
        ));
        assert!(
            manifest.contains("\n[workspace]\n"),
            "it is its own workspace"
        );
    }

    #[test]
    fn a_released_preview_is_named_by_its_version() {
        let manifest = Runner {
            released: true,
            ..runner()
        }
        .manifest();
        assert!(manifest.contains(&format!(
            "morningstar-preview = \"={}\"",
            env!("CARGO_PKG_VERSION")
        )));
        assert!(!manifest.contains("tools/morningstar-preview"));
        // This checkout is not a release.
        assert!(!Runner::new("barua-talk", Path::new("/w")).released);
    }

    #[test]
    fn the_main_file_is_the_same_for_every_app() {
        let main = runner().main_rs();
        assert!(main.contains("use app as _;"));
        assert!(main.contains("fn __morningstar_create_app()"));
        assert!(main.contains("morningstar_preview::host::run(create)"));
        assert!(!main.contains("barua"), "nothing of the app is in it");
        let other = Runner {
            package: "showcase".to_owned(),
            ..runner()
        };
        assert_eq!(main, other.main_rs());
    }

    #[test]
    fn paths_with_quotes_and_backslashes_stay_one_string() {
        assert_eq!(toml_string(r#"a "b" \c"#), r#""a \"b\" \\c""#);
        assert_eq!(toml_string("tab\there"), "\"tab\\there\"");
        assert_eq!(toml_string("bell\u{7}"), "\"bell\\u0007\"");
    }

    #[test]
    fn writing_twice_touches_nothing_the_second_time() {
        let dir = std::env::temp_dir().join(format!("ms-preview-runner-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let manifest = runner().write(&dir).unwrap();
        assert_eq!(manifest, dir.join("Cargo.toml"));
        let first = fs::metadata(&manifest).unwrap().modified().unwrap();
        let main_first = fs::metadata(dir.join("src/main.rs"))
            .unwrap()
            .modified()
            .unwrap();
        std::thread::sleep(std::time::Duration::from_millis(20));
        runner().write(&dir).unwrap();
        assert_eq!(fs::metadata(&manifest).unwrap().modified().unwrap(), first);
        assert_eq!(
            fs::metadata(dir.join("src/main.rs"))
                .unwrap()
                .modified()
                .unwrap(),
            main_first
        );

        // Another app in the same place is written.
        let other = Runner {
            package: "showcase".to_owned(),
            ..runner()
        };
        other.write(&dir).unwrap();
        assert!(
            fs::read_to_string(&manifest)
                .unwrap()
                .contains("preview-showcase")
        );
        fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn the_lock_is_copied_when_missing_and_when_the_workspace_moved_on() {
        let base = std::env::temp_dir().join(format!("ms-preview-lock-{}", std::process::id()));
        let _ = fs::remove_dir_all(&base);
        let (root, runner_dir) = (base.join("ws"), base.join("runner"));
        fs::create_dir_all(&root).unwrap();
        fs::create_dir_all(&runner_dir).unwrap();

        assert!(!sync_lock(&root, &runner_dir).unwrap(), "no lock: nothing");
        fs::write(root.join("Cargo.lock"), "one").unwrap();
        assert!(sync_lock(&root, &runner_dir).unwrap());
        assert_eq!(
            fs::read_to_string(runner_dir.join("Cargo.lock")).unwrap(),
            "one"
        );
        assert!(
            !sync_lock(&root, &runner_dir).unwrap(),
            "the copy is not older"
        );
        fs::remove_dir_all(&base).unwrap();
    }

    #[test]
    fn the_workspace_is_read_from_cargo_metadata() {
        let metadata = r#"{"packages":[{"name":"barua-talk","manifest_path":"/w/examples/barua-talk/Cargo.toml","targets":[]},{"name":"morningstar-ui","manifest_path":"/w/crates/morningstar-ui/Cargo.toml"},{"name":"odd","manifest_path":"/w/a \"b\"\\c/Cargo.toml"}],"workspace_members":[],"target_directory":"/w/target","version":1,"workspace_root":"/w"}"#;
        let workspace = Workspace::from_cargo_metadata(metadata).unwrap();
        assert_eq!(workspace.root, PathBuf::from("/w"));
        assert_eq!(workspace.target_dir, PathBuf::from("/w/target"));
        assert_eq!(
            workspace.members,
            vec![
                PathBuf::from("/w/a \"b\"\\c"),
                PathBuf::from("/w/crates/morningstar-ui"),
                PathBuf::from("/w/examples/barua-talk"),
            ]
        );
        assert_eq!(Workspace::from_cargo_metadata("{}"), None);
    }
}
